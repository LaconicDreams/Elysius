def decay_processor(pack, name):
    rules = []
    for src, dst, p in (("polished_blackstone_bricks", "cracked_polished_blackstone_bricks", 0.25),
                        ("deepslate_bricks", "cracked_deepslate_bricks", 0.25),
                        ("deepslate_tiles", "cracked_deepslate_tiles", 0.15)):
        rules.append({"input_predicate": {"block": f"minecraft:{src}", "predicate_type": "minecraft:random_block_match",
                                          "probability": p},
                      "location_predicate": {"predicate_type": "minecraft:always_true"},
                      "output_state": {"Name": f"minecraft:{dst}"}})
    pack.json(f"data/{NS}/worldgen/processor_list/{name}.json",
              {"processors": [{"processor_type": "minecraft:rule", "rules": rules}]})
    return f"{NS}:{name}"


def template_pool(pack, path, pieces, processors):
    """pieces: list of (structure path, weight)"""
    pack.json(f"data/{NS}/worldgen/template_pool/{path}.json", {
        "elements": [{"element": {"element_type": "minecraft:single_pool_element", "location": f"{NS}:{loc}",
                                  "processors": processors, "projection": "rigid"}, "weight": w}
                     for loc, w in pieces],
        "fallback": "minecraft:empty"})
    return f"{NS}:{path}"


