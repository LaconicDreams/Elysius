def build():
    import dungeons_p3
    pack = Pack(NS, "Elytra modpack boss dungeons (generated by questtools/dungeongen.py)")
    ashen_barrow(pack)
    spire = dungeons_p3.storm_spire(pack, NS, template_pool)
    hollow = dungeons_p3.hollow(pack, NS, template_pool)
    core(pack, [(BAR, "Ashen Warlord", "red", 300), spire["bossbar"], hollow["bossbar"]])
    return pack


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    try:
        pack = build()
    except BuildError as e:
        print(f"ERROR: {e}")
        return 2
    kinds = {}
    for rel in pack.files:
        k = rel.split("/")[2] if rel.startswith("data/") and rel.count("/") >= 3 else rel
        kinds[k] = kinds.get(k, 0) + 1
    print("Pack contents:", ", ".join(f"{v} {k}" for k, v in sorted(kinds.items())))
    rp = resource_pack()
    print(f"Resource pack: {len(rp)} files")
    if "--check" in argv:
        return 0
    n = write_tree(PACK_DIR, pack.files, "datapack")
    print(f"Wrote {n} files to minecraft/config/paxi/datapacks/{NS}")
    n = write_tree(RP_DIR, rp, "resource pack")
    print(f"Wrote {n} files to minecraft/config/paxi/resourcepacks/{NS}_rp")
    return 0


if __name__ == "__main__":
    sys.exit(main())
