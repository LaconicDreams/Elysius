"""
Boss dungeon datapack generator  ->  minecraft/config/paxi/datapacks/elytra_dungeons
====================================================================================
Paxi loads that folder into every world. Structures only appear in chunks generated after the
pack is installed (use /place to test in old areas).

    py dungeongen.py          build the pack (the old pack is backed up to backup/<time>_elytra_dungeons first)
    py dungeongen.py --check  build in memory and report, write nothing

Dungeons so far:
  ashen_barrow  ground ruin in badlands/savanna/desert/volcanic biomes. A spiral shaft leads down to
                a corridor and an underground arena where the Ashen Warlord (wither skeleton) waits.

Fight logic is plain functions (no mod needed): a marker entity saved inside the arena structure
starts the fight when a player comes within 10 blocks; a 5-tick loop tracks boss health for phases,
spawns waves, keeps the boss in the arena, resets if everyone leaves, and pays out on victory.
"""

