def ab_entrance():
    """11 x 28 x 11. y=19 is the ground surface, y=20+ the ruin above ground, y=0..18 the shaft."""
    t = Template(11, 28, 11)
    t.fill(0, 0, 0, 10, 0, 10, "deepslate_tiles")                       # foundation
    t.hollow(0, 0, 0, 10, 20, 10, "deepslate_bricks")                  # shaft walls (top/bottom replaced below)
    t.fill(1, 1, 1, 9, 1, 9, "polished_blackstone_bricks")             # landing floor
    t.fill(4, 1, 4, 6, 1, 6, "water")                                   # 1-deep pool: jump down safely
    t.fill(1, 2, 1, 9, 27, 9, "air")                                    # open shaft + clear the pit above ground
    t.fill(0, 19, 0, 10, 19, 10, "polished_blackstone_bricks")          # rim at ground level
    t.fill(1, 19, 1, 9, 19, 9, "air")                                   # shaft opening
    t.fill(0, 20, 0, 10, 27, 10, "air")                                 # excavated pit above the rim
    # spiral of stairs down the north-east walls (17 steps, from y=18 to y=2)
    path = [(9, z) for z in range(9, 0, -1)] + [(x, 1) for x in range(8, 0, -1)]
    for k, (x, z) in enumerate(path, start=1):
        y = 19 - k
        if (x, z) == (9, 1):
            t.set(x, y, z, "polished_blackstone_bricks")
        elif x == 9:
            t.set(x, y, z, "polished_blackstone_brick_stairs[facing=south,half=bottom,shape=straight,waterlogged=false]")
        else:
            t.set(x, y, z, "polished_blackstone_brick_stairs[facing=east,half=bottom,shape=straight,waterlogged=false]")
    # doorway out of the shaft (north wall), jigsaw at feet level
    t.fill(4, 2, 0, 6, 4, 0, "air")
    out_, in_ = jig_names()
    t.jigsaw(5, 2, 0, "north", out_, in_, f"{NS}:{AB}/corridors")
    # lights
    for x, z in ((9, 9), (1, 9), (9, 2)):
        t.set(x, 2, z, "soul_lantern[hanging=false,waterlogged=false]")
    t.fill(5, 12, 5, 5, 18, 5, "chain[axis=y,waterlogged=false]")
    t.set(5, 11, 5, "soul_lantern[hanging=true,waterlogged=false]")
    # ruin on the rim
    walls = "polished_blackstone_brick_wall[east=none,north=none,south=none,west=none,up=true,waterlogged=false]"
    for (x, z, h) in ((0, 0, 6), (10, 0, 3), (0, 10, 4), (10, 10, 1), (5, 0, 2), (0, 5, 3), (10, 5, 2)):
        t.fill(x, 20, z, x, 19 + h, z, "chiseled_polished_blackstone")
    t.set(0, 26, 0, "wither_skeleton_skull[rotation=10]")
    for x in (1, 2, 3, 7, 8):
        t.set(x, 20, 0, walls)
    for z in (1, 2, 7, 8, 9):
        t.set(0, 20, z, walls)
    t.set(1, 21, 0, walls)
    t.set(0, 21, 2, walls)
    t.set(10, 20, 2, walls)
    t.set(3, 20, 10, walls)
    t.set(4, 20, 10, "gilded_blackstone")
    t.set(10, 20, 7, "soul_campfire[facing=west,lit=true,signal_fire=false,waterlogged=false]")
    t.set(2, 20, 10, "cobweb")
    return t


