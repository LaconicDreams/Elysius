def resource_pack():
    """Client textures (loaded for everyone by Paxi). Only entity types that never spawn naturally are
    retextured, so nothing else in the game changes: the illusioner becomes the Hollow Magus."""
    import zipfile
    import pngtool
    from structlib import _client_jar_path
    files = {"pack.mcmeta": json.dumps({"pack": {"pack_format": 15, "description":
                                                 "Elytra modpack boss skins (generated by questtools/dungeongen.py)"}},
                                       indent=2).encode()}
    with zipfile.ZipFile(_client_jar_path()) as z:
        tex = "assets/minecraft/textures/entity/illager/illusioner.png"
        w, h, px = pngtool.read(z.read(tex))
        files[tex] = pngtool.write(w, h, pngtool.void_recolor(px))
        # Tempest Herald body: a ghast-shaped item model shown by an item_display entity. It is bound to
        # paper with CustomModelData 7101 (all other paper looks normal), so real ghasts are untouched.
        w, h, px = pngtool.read(z.read("assets/minecraft/textures/entity/ghast/ghast.png"))
        files[f"assets/{NS}/textures/item/tempest_herald.png"] = pngtool.write(*pngtool.storm_ghast(w, h, px))
        paper = json.loads(z.read("assets/minecraft/models/item/paper.json"))
    paper["overrides"] = [{"predicate": {"custom_model_data": 7101}, "model": f"{NS}:item/tempest_herald"}]
    files["assets/minecraft/models/item/paper.json"] = json.dumps(paper, indent=2).encode()
    files[f"assets/{NS}/models/item/tempest_herald.json"] = json.dumps(herald_model(), indent=1).encode()
    return files


def herald_model():
    """Ghast shape in model units (16 = one block): 16^3 head + 9 tentacles. UVs are 0..16 over the 64x64
    texture, so 1 unit = 4 px. Face + ruby on both the south and north faces (no wrong side to look at)."""
    t = "#body"
    head = {"from": [0, 0, 0], "to": [16, 16, 16], "faces": {
        "up": {"uv": [4, 0, 8, 4], "texture": t}, "down": {"uv": [8, 0, 12, 4], "texture": t},
        "west": {"uv": [0, 4, 4, 8], "texture": t}, "east": {"uv": [8, 4, 12, 8], "texture": t},
        "south": {"uv": [4, 4, 8, 8], "texture": t}, "north": {"uv": [4, 4, 8, 8], "texture": t}}}
    elements = [head]
    lengths = [11, 9, 13, 8, 14, 10, 12, 9, 11]
    for i, (x, z) in enumerate((x, z) for z in (2, 7, 12) for x in (2, 7, 12)):
        x += 1 if (z == 7) else 0
        ln = lengths[i]
        v2 = 0.5 + ln / 4
        elements.append({"from": [x, -ln, z], "to": [x + 2, 0, z + 2], "faces": {
            "west": {"uv": [0, 0.5, 0.5, v2], "texture": t}, "south": {"uv": [0.5, 0.5, 1, v2], "texture": t},
            "east": {"uv": [1, 0.5, 1.5, v2], "texture": t}, "north": {"uv": [1.5, 0.5, 2, v2], "texture": t},
            "down": {"uv": [0.5, 0, 1, 0.5], "texture": t}}})
    return {"textures": {"body": f"{NS}:item/tempest_herald", "particle": f"{NS}:item/tempest_herald"},
            "elements": elements}


def write_tree(root, files, label):
    if os.path.exists(root):
        stamp = datetime.datetime.now().strftime("%Y-%m-%d_%H%M%S")
        dst = os.path.join(BACKUP_ROOT, f"{stamp}_{os.path.basename(root)}")
        shutil.copytree(root, dst)
        shutil.rmtree(root)
        print(f"Old {label} backed up to backup/{os.path.basename(dst)}")
    for rel, data in files.items():
        p = os.path.join(root, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "wb") as f:
            f.write(data)
    return len(files)
BACKUP_ROOT = os.path.join(gamedata.INSTANCE, "backup")


